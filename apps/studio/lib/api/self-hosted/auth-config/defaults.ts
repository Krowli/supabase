/**
 * `DEFAULTS` is module state shared by every request, so it is frozen one level deep: the two
 * nested `*_CUSTOM_CONTENTS` objects are the only values a caller could otherwise mutate in place,
 * and a mutation there would outlive the request that made it.
 */
type FrozenDefaults = {
  readonly [K in keyof GoTrueConfigResponse]?: Readonly<GoTrueConfigResponse[K]>
}

